BEGIN;


-- =========================================================
-- USERS
-- =========================================================

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    username VARCHAR(64) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,

    role VARCHAR(16) NOT NULL,

    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_users_username
        UNIQUE (username),

    CONSTRAINT uk_users_email
        UNIQUE (email),

    CONSTRAINT chk_users_username_not_blank
        CHECK (btrim(username) <> ''),

    CONSTRAINT chk_users_email_not_blank
        CHECK (btrim(email) <> ''),

    CONSTRAINT chk_users_password_hash_not_blank
        CHECK (btrim(password_hash) <> ''),

    CONSTRAINT chk_users_role
        CHECK (role IN ('ADMIN', 'USER'))
);


-- =========================================================
-- STUDENTS
-- =========================================================

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    fullname VARCHAR(255) NOT NULL,

    isuid INTEGER NOT NULL,

    student_group VARCHAR(255) NOT NULL,

    dormitorynumber INTEGER NOT NULL,

    roomnumber INTEGER NOT NULL,

    moveindate DATE NOT NULL,

    isforeign BOOLEAN NOT NULL,

    notes VARCHAR(255),

    CONSTRAINT uq_students_isuid
        UNIQUE (isuid),

    CONSTRAINT chk_students_fullname_not_blank
        CHECK (btrim(fullname) <> ''),

    CONSTRAINT chk_students_isuid
        CHECK (isuid BETWEEN 100000 AND 999999),

    CONSTRAINT chk_students_group_format
        CHECK (
            student_group ~ '^[A-Z][1-9][1-4][0-9]{2}$'
        ),

    CONSTRAINT chk_students_dormitory
        CHECK (
            dormitorynumber BETWEEN 1 AND 99
        ),

    CONSTRAINT chk_students_room
        CHECK (
            roomnumber BETWEEN 1 AND 9999
        ),

    CONSTRAINT chk_students_move_in_date
        CHECK (
            moveindate < CURRENT_DATE
        )
);


-- =========================================================
-- REFRESH TOKENS
-- =========================================================

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    token_hash VARCHAR(64) NOT NULL,

    user_id BIGINT NOT NULL,

    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,

    revoked BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT uq_refresh_tokens_token_hash
        UNIQUE (token_hash),

    CONSTRAINT fk_refresh_tokens_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
);


-- Индекс полезен для поиска refresh-токенов пользователя.
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_user_id
    ON refresh_tokens(user_id);


-- Может пригодиться при очистке истёкших refresh-токенов.
CREATE INDEX IF NOT EXISTS idx_refresh_tokens_expires_at
    ON refresh_tokens(expires_at);


COMMIT;